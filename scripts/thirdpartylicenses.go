//go:build ignore

// Command thirdpartylicenses regenerates THIRD_PARTY_LICENSES from the Go
// modules linked into the cedrazeka binary (phase 1, step 1.6).
//
//	go run scripts/thirdpartylicenses.go          # rewrite THIRD_PARTY_LICENSES
//	go run scripts/thirdpartylicenses.go -check   # exit 1 if the file is stale
//
// It uses only `go list` and the local module cache; it makes no network calls.
// Modules without a license file, or with a license outside the allowlist
// (docs/legal/provenance.md), are an error: a human must review them.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const outFile = "THIRD_PARTY_LICENSES"

// Release targets whose dependency graphs are merged.
var targets = [][2]string{{"linux", "amd64"}, {"linux", "arm64"}, {"darwin", "arm64"}, {"darwin", "amd64"}}

// In-tree third-party code (provenance.md §1) with its own license file.
var inTree = []struct{ title, path string }{
	{"internal/websocket (fork of github.com/gorilla/websocket)", "internal/websocket/LICENSE"},
	{"internal/config/envconfig (fork of github.com/kelseyhightower/envconfig)", "internal/config/envconfig/LICENSE"},
}

var licenseName = regexp.MustCompile(`(?i)^(licen[cs]e|copying|unlicense)([.-].*)?$`)
var noticeName = regexp.MustCompile(`(?i)^notice(\..*)?$`)

type module struct {
	Path, Version, Dir string
	Main               bool
	Replace            *module
}

func main() {
	check := flag.Bool("check", false, "verify THIRD_PARTY_LICENSES is up to date")
	flag.Parse()

	out, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
	if *check {
		cur, _ := os.ReadFile(outFile)
		if !bytes.Equal(cur, out) {
			fmt.Fprintf(os.Stderr, "%s is stale: run `go run scripts/thirdpartylicenses.go`\n", outFile)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(outFile, out, 0o644); err != nil { //nolint:gosec // a repository file: must be world-readable
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func generate() ([]byte, error) {
	mods := map[string]module{}
	for _, t := range targets {
		cmd := exec.Command("go", "list", "-deps", "-json=Module", ".")
		cmd.Env = append(os.Environ(), "GOOS="+t[0], "GOARCH="+t[1], "GOFLAGS=-mod=readonly")
		cmd.Stderr = os.Stderr
		raw, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list for %s/%s: %w", t[0], t[1], err)
		}
		dec := json.NewDecoder(bytes.NewReader(raw))
		for dec.More() {
			var pkg struct{ Module *module }
			if err := dec.Decode(&pkg); err != nil {
				return nil, err
			}
			m := pkg.Module
			if m == nil || m.Main {
				continue // standard library or our own module
			}
			if m.Replace != nil {
				m.Version, m.Dir = m.Replace.Path+" "+m.Replace.Version, m.Replace.Dir
			}
			mods[m.Path] = *m
		}
	}
	paths := make([]string, 0, len(mods))
	for p := range mods {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b bytes.Buffer
	b.WriteString("Third-party licenses for software included in Cedrazeka.\n")
	b.WriteString("Generated by `go run scripts/thirdpartylicenses.go` - do not edit by hand.\n")
	b.WriteString("Origins and obligations: docs/legal/provenance.md. Cedrazeka itself and\n")
	b.WriteString("Centrifugo OSS (Apache-2.0) are covered by LICENSE and NOTICE.\n")
	b.WriteString("NOTICE files of dependencies are reproduced below their licenses\n(Apache-2.0 section 4(d)).\n")

	for _, it := range inTree {
		text, err := os.ReadFile(it.path)
		if err != nil {
			return nil, err
		}
		if err := section(&b, it.title, string(text), ""); err != nil {
			return nil, err
		}
	}

	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return nil, err
	}
	gl, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(goroot)), "LICENSE"))
	if err != nil {
		return nil, err
	}
	if err := section(&b, "Go standard library and runtime (golang.org)", string(gl), ""); err != nil {
		return nil, err
	}

	var problems []string
	for _, p := range paths {
		m := mods[p]
		lic, notice, err := readLegalFiles(m.Dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", p, err)
		}
		if lic == "" {
			problems = append(problems, p+": no license file in "+m.Dir)
			continue
		}
		if err := section(&b, p+" "+m.Version, lic, notice); err != nil {
			problems = append(problems, p+": "+err.Error())
		}
	}
	if len(problems) > 0 {
		return nil, fmt.Errorf("modules need review:\n  %s", strings.Join(problems, "\n  "))
	}
	return b.Bytes(), nil
}

func readLegalFiles(dir string) (license, notice string, err error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", "", err
	}
	var lic, not []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		switch {
		case licenseName.MatchString(e.Name()):
			lic = append(lic, e.Name())
		case noticeName.MatchString(e.Name()):
			not = append(not, e.Name())
		}
	}
	sort.Strings(lic)
	sort.Strings(not)
	read := func(names []string) (string, error) {
		var parts []string
		for _, n := range names {
			t, err := os.ReadFile(filepath.Join(dir, n)) //nolint:gosec // paths come from go list / the module cache, not user input
			if err != nil {
				return "", err
			}
			parts = append(parts, strings.TrimSpace(string(t)))
		}
		return strings.Join(parts, "\n\n"), nil
	}
	if license, err = read(lic); err != nil {
		return "", "", err
	}
	notice, err = read(not)
	return license, notice, err
}

// classify returns the SPDX ID for the allowlisted licenses, or "" if unknown.
// When several license files are present (e.g. dual licensing), the first match wins.
func classify(text string) string {
	t := strings.Join(strings.Fields(text), " ")
	switch {
	case strings.Contains(t, "Apache License") && strings.Contains(t, "Version 2.0"):
		return "Apache-2.0"
	case strings.Contains(t, "Mozilla Public License") && strings.Contains(t, "2.0"):
		return "MPL-2.0"
	case strings.Contains(t, "Permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(t, "Permission to use, copy, modify, and/or distribute this software for any purpose"),
		strings.Contains(t, "Permission to use, copy, modify, and distribute this software for any purpose"):
		return "ISC"
	case strings.Contains(t, "Redistribution and use in source and binary forms"):
		if strings.Contains(t, "Neither the name") || strings.Contains(t, "names of its contributors may") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	}
	return ""
}

func section(b *bytes.Buffer, title, license, notice string) error {
	id := classify(license)
	if id == "" {
		return fmt.Errorf("license not in allowlist (MIT, BSD-2/3, Apache-2.0, ISC, MPL-2.0)")
	}
	fmt.Fprintf(b, "\n%s\n%s (%s)\n%s\n\n%s\n", strings.Repeat("=", 78), title, id, strings.Repeat("=", 78), strings.TrimSpace(license))
	if notice != "" {
		fmt.Fprintf(b, "\n--- NOTICE ---\n\n%s\n", strings.TrimSpace(notice))
	}
	return nil
}
